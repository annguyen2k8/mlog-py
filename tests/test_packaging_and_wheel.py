"""End-to-end packaging and distribution tests for mlog-py.

Verifies:
1. Clean wheel build containing PEP 561 marker (py.typed) and typing stubs (*.pyi).
2. Elimination of the internal 'src' namespace from distribution wheel.
3. Clean virtualenv installation and execution of CLI entrypoints ('mlog', 'mlog-py').
4. Full runtime API imports ('from mlog import ...', 'from mlog.decompiler import ...').
5. Resilience against local 'src/' directory name shadowing collisions.
"""

import os
import shutil
import subprocess
import sys
import tempfile
import unittest
import zipfile


REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


class TestPackagingAndWheel(unittest.TestCase):
    """Verifies that mlog-py packages cleanly without polluting global namespaces."""

    @classmethod
    def setUpClass(cls):
        """Build the binary wheel once for all packaging tests."""
        cls.temp_dir = tempfile.mkdtemp(prefix="mlog_pkg_test_")
        cls.wheel_dir = os.path.join(cls.temp_dir, "wheel")
        cls.venv_dir = os.path.join(cls.temp_dir, "venv")
        os.makedirs(cls.wheel_dir, exist_ok=True)

        # Build wheel in isolation using build module
        proc = subprocess.run(
            [sys.executable, "-m", "build", "--wheel", "--outdir", cls.wheel_dir, REPO_ROOT],
            capture_output=True,
            text=True,
        )
        if proc.returncode != 0:
            shutil.rmtree(cls.temp_dir, ignore_errors=True)
            raise RuntimeError(f"Wheel build failed:\nSTDOUT:\n{proc.stdout}\nSTDERR:\n{proc.stderr}")

        wheels = [f for f in os.listdir(cls.wheel_dir) if f.endswith(".whl")]
        if not wheels:
            shutil.rmtree(cls.temp_dir, ignore_errors=True)
            raise RuntimeError("No .whl file generated by build.")

        cls.wheel_path = os.path.join(cls.wheel_dir, wheels[0])

        # Create clean virtualenv
        subprocess.run(
            [sys.executable, "-m", "venv", cls.venv_dir],
            check=True,
            capture_output=True,
        )

        # Locate venv python and pip binaries
        if sys.platform == "win32":
            cls.venv_python = os.path.join(cls.venv_dir, "Scripts", "python.exe")
            cls.venv_pip = os.path.join(cls.venv_dir, "Scripts", "pip.exe")
            cls.venv_scripts_dir = os.path.join(cls.venv_dir, "Scripts")
        else:
            cls.venv_python = os.path.join(cls.venv_dir, "bin", "python")
            cls.venv_pip = os.path.join(cls.venv_dir, "bin", "pip")
            cls.venv_scripts_dir = os.path.join(cls.venv_dir, "bin")

        # Install wheel into clean virtualenv
        install_proc = subprocess.run(
            [cls.venv_pip, "install", cls.wheel_path],
            capture_output=True,
            text=True,
        )
        if install_proc.returncode != 0:
            shutil.rmtree(cls.temp_dir, ignore_errors=True)
            raise RuntimeError(f"Pip install failed:\n{install_proc.stderr}")

    @classmethod
    def tearDownClass(cls):
        """Clean up temporary test virtualenv and wheel artifacts."""
        shutil.rmtree(cls.temp_dir, ignore_errors=True)

    def test_wheel_contents_and_pep561_assets(self):
        """Wheel must contain PEP 561 py.typed, typing stubs, and no 'src/' prefix."""
        with zipfile.ZipFile(self.wheel_path, "r") as zf:
            namelist = zf.namelist()

        # 1. Must contain proper package files
        self.assertIn("mlog/__init__.py", namelist)
        self.assertIn("mlog/__main__.py", namelist)

        # 2. Must contain PEP 561 marker and canonical typing stub (no duplicate)
        self.assertIn("mlog/py.typed", namelist)
        self.assertIn("mlog/__init__.pyi", namelist)
        self.assertNotIn("mlog/mlog.pyi", namelist)

        # 3. Must NOT contain top-level 'src/' directory
        src_files = [f for f in namelist if f.startswith("src/")]
        self.assertEqual(
            src_files,
            [],
            f"Wheel should not package internal 'src/' directory into site-packages: {src_files}",
        )

        # 4. Must NOT package root compiler.py or mlog.py as loose modules
        self.assertNotIn("compiler.py", namelist)
        self.assertNotIn("mlog.py", namelist)

    def test_clean_site_packages_has_no_src_directory(self):
        """Site-packages must not contain any 'src' folder after installation."""
        check_code = (
            "import sys, os\n"
            "site_packages = [p for p in sys.path if 'site-packages' in p][0]\n"
            "src_path = os.path.join(site_packages, 'src')\n"
            "print('EXISTS' if os.path.exists(src_path) else 'CLEAN')\n"
        )
        proc = subprocess.run(
            [self.venv_python, "-c", check_code],
            capture_output=True,
            text=True,
            check=True,
        )
        self.assertEqual(proc.stdout.strip(), "CLEAN")

    def test_outside_project_cannot_import_internal_src(self):
        """In an outside project, 'import src' fails because 'src' is never installed."""
        with tempfile.TemporaryDirectory(prefix="empty_project_") as proj_dir:
            test_script = (
                "import sys\n"
                "try:\n"
                "    import src\n"
                "    print('UNEXPECTED_SRC_FOUND')\n"
                "except ModuleNotFoundError:\n"
                "    print('SRC_NOT_FOUND_AS_EXPECTED')\n"
            )
            proc = subprocess.run(
                [self.venv_python, "-c", test_script],
                cwd=proj_dir,
                capture_output=True,
                text=True,
            )
            self.assertEqual(proc.returncode, 0)
            self.assertIn("SRC_NOT_FOUND_AS_EXPECTED", proc.stdout)

    def test_clean_venv_public_api_imports(self):
        """Verify official public APIs import cleanly from installed wheel."""
        check_code = (
            "import mlog\n"
            "from mlog import compile_py, decompile, decompile_with_source_map, sensor, control, wait\n"
            "from mlog.compiler import Compiler\n"
            "from mlog.decompiler import decompile as decomp_direct\n"
            "# Run basic compilation and decompilation\n"
            "comp_res = compile_py('x = 10\\n')\n"
            "assert 'set x 10' in comp_res.mlog\n"
            "decomp_code = decompile('set y 20\\n')\n"
            "assert 'y = 20' in decomp_code\n"
        )
        proc = subprocess.run(
            [self.venv_python, "-c", check_code],
            capture_output=True,
            text=True,
        )
        self.assertEqual(proc.returncode, 0, f"Public API test failed:\n{proc.stderr}")

    def test_clean_venv_cli_entrypoints(self):
        """Both 'mlog' and 'mlog-py' executable scripts and 'python -m mlog' must work."""
        mlog_cmd = os.path.join(self.venv_scripts_dir, "mlog")
        mlog_py_cmd = os.path.join(self.venv_scripts_dir, "mlog-py")

        # 1. python -m mlog --version
        proc_mod = subprocess.run(
            [self.venv_python, "-m", "mlog", "--version"],
            capture_output=True,
            text=True,
        )
        self.assertEqual(proc_mod.returncode, 0)
        self.assertIn("0.9.0", proc_mod.stdout + proc_mod.stderr)

        # 2. mlog-py --help
        proc_py = subprocess.run(
            [mlog_py_cmd, "--help"],
            capture_output=True,
            text=True,
        )
        self.assertEqual(proc_py.returncode, 0)
        self.assertIn("usage:", proc_py.stdout)

        # 3. mlog alias --help
        proc_alias = subprocess.run(
            [mlog_cmd, "--help"],
            capture_output=True,
            text=True,
        )
        self.assertEqual(proc_alias.returncode, 0)
        self.assertIn("usage:", proc_alias.stdout)

    def test_shadowing_resilience_in_user_project_with_src(self):
        """A user repo with a local 'src/' folder must never break mlog imports or decompiler."""
        with tempfile.TemporaryDirectory(prefix="user_project_") as proj_dir:
            user_src = os.path.join(proj_dir, "src")
            os.makedirs(user_src)
            with open(os.path.join(user_src, "__init__.py"), "w") as f:
                f.write("# User own project source code\n")
            with open(os.path.join(user_src, "main.py"), "w") as f:
                f.write("print('user project')\n")

            test_script = (
                "import sys\n"
                "# In user project with local src/\n"
                "from mlog import compile_py, decompile\n"
                "res = compile_py('x = 42\\n')\n"
                "assert 'set x 42' in res.mlog\n"
                "py_out = decompile('set a 100\\n')\n"
                "assert 'a = 100' in py_out\n"
                "print('SHADOWING_TEST_PASS')\n"
            )

            proc = subprocess.run(
                [self.venv_python, "-c", test_script],
                cwd=proj_dir,
                capture_output=True,
                text=True,
            )
            self.assertEqual(
                proc.returncode,
                0,
                f"Failed inside user project with local src/:\n{proc.stderr}",
            )
            self.assertIn("SHADOWING_TEST_PASS", proc.stdout)

    def test_pyright_clean_wheel_typing_verification(self):
        """Verify installed wheel typing stubs using Pyright if available."""
        # Find pyright binary or node runner
        pyright_cmd = None
        cli = shutil.which("pyright")
        if cli:
            pyright_cmd = [cli]
        else:
            node = shutil.which("node")
            if node:
                npm_npx = os.path.expanduser("~/.npm/_npx")
                if os.path.isdir(npm_npx):
                    for root, dirs, files in os.walk(npm_npx):
                        if "index.js" in files and os.path.basename(root) == "pyright":
                            pyright_cmd = [node, os.path.join(root, "index.js")]
                            break

        if not pyright_cmd:
            self.skipTest("Pyright type checker is not installed in the environment.")

        with tempfile.TemporaryDirectory(prefix="pyright_run_") as run_dir:
            test_file = os.path.join(run_dir, "type_test.py")
            with open(test_file, "w", encoding="utf-8") as f:
                f.write(
                    "from typing import Any, Tuple\n"
                    "import mlog\n"
                    "from mlog.errors import CompileError, SourceLocation\n"
                    "from mlog import (\n"
                    "    compile_py,\n"
                    "    decompile,\n"
                    "    decompile_with_source_map,\n"
                    "    CompileResult,\n"
                    "    null,\n"
                    "    Vars,\n"
                    "    draw,\n"
                    "    control,\n"
                    "    ucontrol,\n"
                    "    ulocate,\n"
                    "    op,\n"
                    "    read,\n"
                    "    write,\n"
                    "    sensor,\n"
                    "    wait,\n"
                    "    stop,\n"
                    "    end,\n"
                    "    packcolor,\n"
                    "    unpackcolor,\n"
                    "    Array,\n"
                    "    Items,\n"
                    "    Liquids,\n"
                    "    Units,\n"
                    "    SensorProperty,\n"
                    "    ControlProperty,\n"
                    "    UnitControl,\n"
                    "    DrawType,\n"
                    "    LogicOp,\n"
                    "    Condition,\n"
                    "    RadarTarget,\n"
                    "    RadarSort,\n"
                    "    LookupType,\n"
                    "    Align,\n"
                    "    IntEnum,\n"
                    ")\n"
                    "\n"
                    "# 1. Compile API\n"
                    "res: CompileResult = compile_py('x = 10', filename='test.py', validate=True, allow_functions=True)\n"
                    "mlog_code: str = res.mlog\n"
                    "\n"
                    "# 2. Decompile API with overload resolution\n"
                    "py_code: str = decompile(mlog_code, filename='test.mlog', debug=False)\n"
                    "source_map_res: Tuple[str, Any] = decompile_with_source_map(mlog_code)\n"
                    "tuple_res: Tuple[str, Any] = decompile(mlog_code, return_source_map=True)\n"
                    "\n"
                    "# 3. Enum re-exports and sub-classing\n"
                    "class CustomEnum(IntEnum):\n"
                    "    ALPHA = 1\n"
                    "    BETA = 2\n"
                    "\n"
                    "item_coal: Items = Items.COAL\n"
                    "prop_hp: SensorProperty = SensorProperty.HEALTH\n"
                    "\n"
                    "# 4. Typed intrinsics\n"
                    "r_val: Any = read('cell1', 0)\n"
                    "write(r_val, 'cell1', 0)\n"
                    "wait(0.5)\n"
                    "stop()\n"
                    "end()\n"
                    "\n"
                    "# 5. Array API\n"
                    "arr: Array = Array('cell1', size=64, dtype=int)\n"
                    "first_item: Any = arr[0]\n"
                    "arr[1] = 42\n"
                    "count: int = len(arr)\n"
                    "\n"
                    "# 6. Null and Vars\n"
                    "null_val: Any = null\n"
                    "var_this: Any = Vars.this\n"
                    "\n"
                    "# 7. Errors\n"
                    "err: CompileError = CompileError('test error', SourceLocation('test.py', 1, 1))\n"
                )

            config_file = os.path.join(run_dir, "pyrightconfig.json")
            venv_parent = os.path.dirname(self.venv_dir)
            venv_name = os.path.basename(self.venv_dir)
            with open(config_file, "w", encoding="utf-8") as f:
                f.write(
                    f'{{\n'
                    f'  "include": ["type_test.py"],\n'
                    f'  "venvPath": "{venv_parent}",\n'
                    f'  "venv": "{venv_name}",\n'
                    f'  "pythonVersion": "3.11"\n'
                    f'}}\n'
                )

            proc = subprocess.run(
                pyright_cmd + ["--project", run_dir],
                capture_output=True,
                text=True,
            )
            self.assertEqual(
                proc.returncode,
                0,
                f"Pyright typing verification failed on clean wheel installation:\nSTDOUT:\n{proc.stdout}\nSTDERR:\n{proc.stderr}",
            )


if __name__ == "__main__":
    unittest.main()
